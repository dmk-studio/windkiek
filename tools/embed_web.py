# PlatformIO pre-build script: compresses web/setup.html and writes it to src/web_page.h
# as a byte array. The device serves it gzip-compressed to the browser.
import gzip
import os

try:
    Import("env")  # noqa: F821  (provided by PlatformIO/SCons)
    root = env["PROJECT_DIR"]  # noqa: F821
except NameError:  # run directly: python tools/embed_web.py
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

src = os.path.join(root, "web", "setup.html")
dst = os.path.join(root, "src", "web_page.h")

with open(src, "rb") as f:
    data = gzip.compress(f.read(), compresslevel=9, mtime=0)

lines = []
for i in range(0, len(data), 20):
    lines.append("  " + ", ".join("0x%02x" % b for b in data[i:i + 20]) + ",")
out = (
    "// Generated by tools/embed_web.py from web/setup.html. Do not edit.\n"
    "#pragma once\n#include <Arduino.h>\n\n"
    "static const uint8_t WEB_PAGE_GZ[] PROGMEM = {\n" + "\n".join(lines) + "\n};\n"
    "static const size_t WEB_PAGE_GZ_LEN = %d;\n" % len(data)
)
old = open(dst).read() if os.path.exists(dst) else ""
if old != out:
    with open(dst, "w") as f:
        f.write(out)
    print("embed_web: %s (%d bytes gzip)" % (dst, len(data)))
