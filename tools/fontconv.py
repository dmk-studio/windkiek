"""Converts TTF files into 1-bit Adafruit GFX fonts (Latin-1).

Usage:  python tools/fontconv.py src/fonts.h      (needs Pillow, see tools/requirements.txt)
Glyphs are rendered with FreeType monochrome hinting, like the ePaper shows them.
In addition to Latin-1: 0x7F = en dash (–), 0x80 = greater-or-equal (≥),
0x81-0x83 = typographic quotes („ “ ”). render.cpp maps UTF-8 to these codes.
"""
import os
import sys

from PIL import Image, ImageDraw, ImageFont

HERE = os.path.dirname(os.path.abspath(__file__))
FONTS = [  # (C name, TTF, pixel size)
    ("Inter800_28", "Inter-800.ttf", 28),
    ("Inter400_16", "Inter-400.ttf", 16),
    ("Inter400_14", "Inter-400.ttf", 14),
    ("Inter800_16", "Inter-800.ttf", 16),
    ("Inter800_12", "Inter-800.ttf", 12),
    ("Inter400_12", "Inter-400.ttf", 12),
    ("Inter800_11", "Inter-800.ttf", 11),
    ("Inter600_11", "Inter-600.ttf", 11),
    ("Inter400_10", "Inter-400.ttf", 10),
    ("Inter600_9", "Inter-600.ttf", 9),
]
FIRST, LAST = 0x20, 0xFF
EXTRA = {0x7F: "–", 0x80: "≥", 0x81: "„", 0x82: "“", 0x83: "”"}
THRESHOLD = 140


def char_for(code):
    if code in EXTRA:
        return EXTRA[code]
    if 0x84 <= code <= 0x9F:  # control characters, empty
        return None
    return chr(code)


def convert(name, ttf, size):
    font = ImageFont.truetype(os.path.join(HERE, "fonts", ttf), size)
    bitmap, glyphs = [], []
    ascent, descent = font.getmetrics()
    for code in range(FIRST, LAST + 1):
        ch = char_for(code)
        if ch is None:
            glyphs.append((len(bitmap), 0, 0, 0, 0, 0))
            continue
        advance = round(font.getlength(ch))
        l, t, r, b = font.getbbox(ch, anchor="ls")
        w, h = r - l, b - t
        if w <= 0 or h <= 0:
            glyphs.append((len(bitmap), 0, 0, advance, 0, 0))
            continue
        img = Image.new("L", (w + 2, h + 2), 255)
        draw = ImageDraw.Draw(img)
        draw.fontmode = "1"  # FreeType monochrome with hinting instead of antialiasing
        draw.text((1 - l, 1 - t), ch, font=font, fill=0, anchor="ls")
        w, h, l, t = w + 2, h + 2, l - 1, t - 1
        px = img.load()
        ink = [[px[x, y] < THRESHOLD for x in range(w)] for y in range(h)]
        # crop to the actual ink
        rows = [y for y in range(h) if any(ink[y])]
        cols = [x for x in range(w) if any(ink[y][x] for y in range(h))]
        if not rows:
            glyphs.append((len(bitmap), 0, 0, advance, 0, 0))
            continue
        y0, y1, x0, x1 = rows[0], rows[-1], cols[0], cols[-1]
        gw, gh = x1 - x0 + 1, y1 - y0 + 1
        offset = len(bitmap)
        acc, nbits = 0, 0
        for y in range(y0, y1 + 1):
            for x in range(x0, x1 + 1):
                acc = (acc << 1) | (1 if ink[y][x] else 0)
                nbits += 1
                if nbits == 8:
                    bitmap.append(acc)
                    acc, nbits = 0, 0
        if nbits:
            bitmap.append(acc << (8 - nbits))
        glyphs.append((offset, gw, gh, advance, l + x0, t + y0))

    out = [f"// {ttf} {size}px, generated by tools/fontconv.py\n"]
    out.append(f"static const uint8_t {name}Bitmaps[] PROGMEM = {{\n")
    for i in range(0, len(bitmap), 16):
        out.append("  " + ", ".join(f"0x{v:02X}" for v in bitmap[i:i + 16]) + ",\n")
    out.append("};\n")
    out.append(f"static const GFXglyph {name}Glyphs[] PROGMEM = {{\n")
    for code, g in zip(range(FIRST, LAST + 1), glyphs):
        out.append(f"  {{{g[0]}, {g[1]}, {g[2]}, {g[3]}, {g[4]}, {g[5]}}},  // 0x{code:02X}\n")
    out.append("};\n")
    out.append(f"static const GFXfont {name} PROGMEM = {{(uint8_t*){name}Bitmaps, (GFXglyph*){name}Glyphs, "
               f"0x{FIRST:02X}, 0x{LAST:02X}, {ascent + descent}}};\n\n")
    return "".join(out)


def main():
    target = sys.argv[1]
    parts = ["#pragma once\n// Generated by tools/fontconv.py. Do not edit.\n// Inter (SIL Open Font License 1.1, see tools/fonts/OFL.txt) as 1-bit GFX fonts\n#include <Adafruit_GFX.h>\n\n"]
    for name, ttf, size in FONTS:
        parts.append(convert(name, ttf, size))
    with open(target, "w", encoding="utf-8") as f:
        f.write("".join(parts))
    print(f"{target}: {len(FONTS)} Fonts")


if __name__ == "__main__":
    main()
